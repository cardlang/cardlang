"""Generate the 'Index of rules' in spec/00-index.md: every rule ID, its status and the section that defines it.

Rerun after adding or moving rules:  python -I tools/generators/rule_index.py .
"""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "checkers"))   # find layout
import layout
repo = pathlib.Path(sys.argv[1]); spec = layout.at(repo).spec
files = sorted(spec.glob("[01][0-9]-*.md")) + [spec / "annex-B-platform-contract.md"]

def anchor(heading):
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")

rows = []
for f in files:
    section = None
    for line in f.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (.+)$", line)
        if m: section = m.group(1)
        m = re.match(r"^\*\*([A-Z]{3}-\d+) \[(\w+)\]\*\*", line)
        if m: rows.append(f"| {m.group(1)} | {m.group(2)} | [{section}]({f.name}#{anchor(section)}) |")

p = spec / "00-index.md"; t = p.read_text(encoding="utf-8")
head, rest = t.split("## Index of rules", 1)
tail = rest[rest.find("\n## "):] if "\n## " in rest else ""
body = ("## Index of rules\n\n<!-- generated by tools/generators/rule_index.py; do not edit by hand -->\n\n"
        f"All {len(rows)} rules, in chapter order. Each chapter is the authority for its own rules.\n\n"
        "| Rule | Status | Defined in |\n|---|---|---|\n" + "\n".join(rows) + "\n")
p.write_text(head + body + tail, encoding="utf-8", newline="\n")
print("rules indexed:", len(rows))
