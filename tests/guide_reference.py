"""The guide's platform reference, generated from the Base Profile and the specification, run by tests/run_checks.py.

Writes guide/docs/reference-platform.md from:
- platform/base-catalog.txt: every card. API, by family;
- platform/base-types.card: the profile's types;
- platform/base-profile.md, the CardError table (BP-12);
- language/spec/13-runtime-failures.md, the trap kinds (RTF-4).

Rerun after changing any of them:  uv run python -I tests/guide_reference.py .
In run_checks, with --check: the page must equal what this would write.
"""
import re, sys, difflib, pathlib
from cardlang import layout

FAMILIES = [("key", "Keys"), ("crypto", "Cryptography"), ("random", "Randomness"),
            ("cbor", "CBOR"), ("der", "DER"), ("tlv", "BER-TLV")]
TRANSACTION = {
    "participates": "takes part: undone if the transaction aborts",
    "immediate": "takes effect at once, even inside a transaction",
    "forbidden": "not allowed inside a transaction",
}
DEFAULT_FAILURE = "nothing changes (BP-7)"

def catalog(text):
    """[(api, {field: value})] in file order."""
    out = []
    for line in text.split("\n"):
        line = line.split("#")[0].rstrip()
        if not line.strip(): continue
        if line.startswith("api "):
            out.append((line[4:].strip(), {}))
        else:
            field, _, value = line.strip().partition(" ")
            out[-1][1][field] = value.strip()
    return out

def types(text):
    """[(comment lines, [(name, declaration)])]: the declarations of base-types.card, in groups led by a comment."""
    groups, comment, decls, cur = [], [], [], None
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"(enum|struct)\s+(\w+)\s*\{", line)
        if m:
            j = i
            while lines[j].strip() != "}": j += 1
            decls.append((m.group(2), "\n".join(lines[i:j + 1])))
            i = j + 1; continue
        if line.startswith("//"):
            if decls:
                groups.append((comment, decls)); comment, decls = [], []
            comment.append(line[2:].strip())
        elif not line.strip() and not decls:
            comment = []                       # a comment not directly above declarations, such as the file's header
        i += 1
    if decls: groups.append((comment, decls))
    return groups[1:] if groups and not groups[0][1] else groups

def card_errors(text):
    return re.findall(r"^\| `(\w+)` \| `0x([0-9A-Fa-f]{4})` \| (.*?) \|\s*$", text, re.M)

def trap_kinds(text):
    body = text[text.index("**RTF-4**"):]
    body = body[:body.index("These names")]
    return re.findall(r"^\| `([A-Z-]+)` \| (.*?) \| (.*?) \|\s*$", body, re.M)

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def render(L):
    apis = catalog(L.base_catalog.read_text(encoding="utf-8"))
    groups = types(L.base_types.read_text(encoding="utf-8"))
    errors = card_errors(L.base_profile.read_text(encoding="utf-8"))
    traps = trap_kinds((L.spec / "13-runtime-failures.md").read_text(encoding="utf-8"))
    type_names = {name for _, decls in groups for name, _ in decls}
    out = ["<!-- Generated by tests/guide_reference.py from the Base Profile and the specification. Do not edit. -->",
           "# Platform reference", "",
           "What the Base Profile gives an applet: its APIs, their types, the platform's errors, and the kinds of trap. "
           "This page is generated from the [Base Profile](https://github.com/cardlang/cardlang/blob/main/platform/base-profile.md), "
           "its [API catalog](https://github.com/cardlang/cardlang/blob/main/platform/base-catalog.txt) and the "
           "[specification](https://github.com/cardlang/cardlang/blob/main/language/spec/00-index.md), so it always "
           "matches them. They are the authority; [chapter 8](08-platform.md) explains how to use the APIs.", "",
           "Every API returns an outcome. Its errors are listed in precedence order: when several apply, it returns the "
           "first (*BP-8*). When an API fails, nothing changes, unless its entry says otherwise (*BP-7*).", ""]
    for family, title in FAMILIES:
        members = [(a, f) for a, f in apis if a.split(".")[1] == family]
        out += [f"## {title}: `card.{family}`", ""]
        for api, f in members:
            params = "" if f["params"] == "-" else f["params"]
            ret = "" if f["payload"] == "-" else f" -> {f['payload']}"
            call = f"{api}({params}){ret}"
            if len(call) > 72:                         # one parameter per line, so it fits a narrow screen
                call = f"{api}(\n" + ",\n".join("    " + p.strip() for p in params.split(",")) + f"\n){ret}"
            out += [f"### `{api}`", "", "<!-- check: none -->", "```cardlang", call, "```", "",
                    f["summary"], ""]
            lines = []
            used = [t for t in type_names if re.search(rf"\b{t}\b", f["params"] + " " + f["payload"])]
            if used:
                lines.append("- **Types:** " + ", ".join(f"[`{t}`](#{slug(t)})" for t in sorted(used)))
            if f["errors"] != "-":
                errs = [e.strip() for e in f["errors"].split(",")]
                lines.append("- **Errors:** " + ", ".join(f"[`{e}`](#carderror-{slug(e)})" for e in errs))
            else:
                lines.append("- **Errors:** none")
            lines.append(f"- **In a transaction:** {TRANSACTION.get(f['transaction'], f['transaction'])}")
            if f.get("resources", "-") != "-":
                lines.append(f"- **Resources:** {f['resources']}")
            if f.get("on-failure") and f["on-failure"] != DEFAULT_FAILURE:
                lines.append(f"- **On failure:** {f['on-failure']}")
            if f.get("permission", "-") != "-":
                lines.append(f"- **Permission:** {f['permission']}")
            out += lines + [""]
    out += ["## Types", "", "The profile's types, declared in "
            "[`base-types.card`](https://github.com/cardlang/cardlang/blob/main/platform/base-types.card). "
            "Every applet is built with them, so their names are taken.", ""]
    for comment, decls in groups:
        out += [" ".join(f'<a id="{slug(n)}"></a>' for n, _ in decls), "", " ".join(comment), "",
                "<!-- check: none -->", "```cardlang", "\n\n".join(d for _, d in decls), "```", ""]
    out += ["## The platform's errors", "",
            "The members of `CardError`, with their codes (*BP-12*). The host sees category `02` and the code in the "
            "raw binding, or status word `6F00` plus the code in the ISO 7816 binding.", "",
            "| Member | Code | Returned by |", "|---|---|---|"]
    for member, code, cause in errors:
        out.append(f'| <a id="carderror-{slug(member)}"></a>`CardError.{member}` | `{code.upper()}` | {cause} |')
    out += ["", "## Trap kinds", "",
            "The kinds of trap (*RTF-4*). Scenarios name them in `expect trap`, and `clc run` and the debugger show "
            "them. The host usually learns only that a trap happened, not its kind (*PLT-10*).", "",
            "| Kind | Raised when | Rules |", "|---|---|---|"]
    for kind, when, rules in traps:
        out.append(f"| `{kind}` | {when} | {rules} |")
    return "\n".join(out) + "\n"

def main(repo, check):
    L = layout.at(repo); page = L.guide / "docs" / "reference-platform.md"
    text = render(L)
    if not check:
        page.write_text(text, encoding="utf-8", newline="\n"); print("wrote", page.relative_to(L.root).as_posix()); return True
    have = page.read_text(encoding="utf-8") if page.exists() else ""
    if have == text:
        print("PASS", page.relative_to(L.root).as_posix(), "| matches the catalog, the types, the CardError table and RTF-4")
        print("ALL PASS"); return True
    diff = list(difflib.unified_diff(have.split("\n"), text.split("\n"), "on disk", "generated", lineterm="", n=0))
    print("FAIL", page.relative_to(L.root).as_posix(), "| out of date; rerun tests/guide_reference.py")
    for line in diff[:20]: print("    " + line)
    print("FAILURES"); return False

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    sys.exit(0 if main(pathlib.Path(args[0]).resolve() if args else None, "--check" in sys.argv) else 1)
