"""One-off (SP13): build the Annex B §B.12 checklist from every 'platform-defined' reference in chapters 1-13 and Annex B."""
import re, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "tools" / "checkers"))   # find layout
import layout
repo = pathlib.Path(sys.argv[1])
rows = []
files = sorted((layout.at(repo).spec).glob("[01][0-9]-*.md")) + [layout.at(repo).spec / "annex-B-platform-contract.md"]
for f in files:
    text = f.read_text(encoding="utf-8")
    for m in re.finditer(r"^\*\*([A-Z]{3}-\d+) \[Agreed\]\*\* (.*?)(?=^\*\*[A-Z]{3}-\d+ |\Z|^## )", text, re.M | re.S):
        rule, body = m.group(1), m.group(2)
        body = body.split("*Sources:")[0]
        for sentence in re.split(r"(?<=[.)])\s+(?=[A-Z])", re.sub(r"\s+", " ", body)):
            if "platform-defined" in sentence.lower():
                rows.append((rule, f.name, sentence.strip()))
out = ["| # | Rule | Item left to the platform |", "|---|---|---|"]
for i, (rule, fname, sentence) in enumerate(rows, 1):
    out.append(f"| {i} | [{rule}]({fname}) | {sentence.replace('|', '/')} |")
p = layout.at(repo).spec / "annex-B-platform-contract.md"
t = p.read_text(encoding="utf-8")
marker = "<!-- B.12 table generated by devel/history/sp13_checklist.py from the \"platform-defined\" references in chapters 1–13 -->"
assert marker in t
head, rest = t.split(marker)
tail = rest[rest.index("\n## "):] if "\n## " in rest else ""        # keep sections after B.12 (WP1 added B.13)
t = head + marker + "\n\n" + "\n".join(out) + "\n" + tail
p.write_text(t, encoding="utf-8", newline="\n")
print("checklist rows:", len(rows))
